import fs from "node:fs";
import assert from "node:assert/strict";
const content = fs.readFileSync("extension/content.js", "utf8");
const overlay = fs.readFileSync("extension/live-caption-overlay.js", "utf8");
const background = fs.readFileSync("extension/background.js", "utf8");
const liveHtml = fs.readFileSync("extension/ui/live.html", "utf8");
const liveJs = fs.readFileSync("extension/ui/live.js", "utf8");
const liveCss = fs.readFileSync("extension/ui/live.css", "utf8");
const scheduleMatch = content.match(/function scheduleMutationWork\(\) \{[\s\S]*?\n  \}/);
assert.ok(scheduleMatch, "mutation scheduler exists");
const schedule = scheduleMatch[0];
assert.match(schedule, /autoAnswer\(\)/, "incoming-call detection remains in mutation path");
assert.match(schedule, /detectAvailability\(\)/, "availability detection remains in mutation path");
assert.match(schedule, /}, 150\);/, "mutation work is coalesced to 150ms");
assert.doesNotMatch(schedule, /mediaSnapshot|mapScreen|renderOverlay|renderCallOverlayControl/, "heavy scans and repaints are removed from mutation hot path");
assert.match(overlay, /var MAX_HISTORY = 800;/, "in-memory caption history remains 800 rows");
assert.match(overlay, /var MAX_RENDERED_ROWS = 72;/, "overlay DOM is capped at 72 spans");
assert.match(overlay, /rows\.slice\(-MAX_RENDERED_ROWS\)/, "only recent spans are expanded for rendering");
assert.match(overlay, /data = data\.slice\(-MAX_RENDERED_ROWS\)/, "rendered span count is bounded");
assert.match(overlay, /class="tool history"/, "overlay exposes transcript tab button");
assert.match(overlay, /type: "OPEN_SIGNAL_LIVE_WINDOW"/, "overlay invokes transcript tab action");
assert.match(background, /chrome\.tabs\.query\(\{url:targetUrl\}\)/, "existing transcript tab is reused");
assert.match(background, /chrome\.tabs\.create\(\{url:targetUrl,active:true\}\)/, "transcript opens in a normal Chrome tab");
assert.doesNotMatch(background.match(/async function openSignalLiveWindow\([\s\S]*?\n  \}/)?.[0] || "", /chrome\.windows\.create/, "transcript action no longer opens a popup window");
assert.match(background, /sender && sender\.tab \? sender\.tab\.id : null/, "content-script sender tab is used when no explicit tab ID is supplied");
assert.match(overlay,/padding:3px 0 4px/,"caption rows use compact vertical spacing");
assert.match(overlay,/font-size:14px;line-height:1\.4/,"caption text remains readable at compact density");
assert.ok(liveHtml.includes('id="toggleTools"'),"LIVE reader exposes a secondary-controls toggle");
assert.match(liveJs,/classList\.add\("reader-fullwidth"\)/,"LIVE reader opens full-width by default");
assert.ok(liveCss.includes("body.reader-fullwidth .controls{display:none}"),"secondary controls do not consume transcript width by default");
console.log("LIVE_CAPTION_PERFORMANCE_BUDGET_TEST=PASS");