import fs from "node:fs";
import crypto from "node:crypto";
import assert from "node:assert/strict";
const meta=JSON.parse(fs.readFileSync("extension/ui/sample.json","utf8"));
const audio=Buffer.from(fs.readFileSync("extension/ui/sample.ogg.b64","ascii").trim(),"base64");
const sha=b=>crypto.createHash("sha256").update(b).digest("hex").toUpperCase();
assert.equal(meta.schema,"signal-caption-lab-sample/v1");
assert.equal(meta.file,"sample.ogg");
assert.equal(meta.durationSeconds,281.6);
assert.ok(Math.abs(meta.source.endSeconds-meta.source.startSeconds-meta.durationSeconds)<0.001);
assert.equal(sha(audio),meta.sha256);
assert.equal(audio.subarray(0,4).toString(),"OggS");
assert.ok(audio.includes(Buffer.from("OpusHead")));
assert.deepEqual(meta.roles,["client-clinician-en","patient-lep-es","interpreter-en-es"]);
assert.equal(meta.realCloudCallValidated,false);
assert.notEqual(sha(Buffer.concat([audio,Buffer.from("damaged")])),meta.sha256);
const html=fs.readFileSync("extension/ui/lab.html","utf8");
assert.ok(html.includes('src="sample.ogg"'));
const installer=fs.readFileSync("INSTALAR.ps1","utf8");
assert.ok(installer.includes("materialize-lab-sample.ps1"));
assert.ok(!installer.includes("SAPI.SpVoice"));
assert.ok(!installer.includes("sample.wav"));
const helper=fs.readFileSync("tools/materialize-lab-sample.ps1","utf8");
assert.ok(helper.includes("FromBase64String"));
assert.ok(helper.includes("Get-FileHash"));
assert.ok(helper.includes("preserve it and prepare a clean package"));
assert.ok(fs.readFileSync("extension/ui/lab.js","utf8").includes('"bundled-sample"'));
assert.ok(fs.readFileSync("extension/caption-lab.js","utf8").includes('"bundled-sample"'));
console.log("BUNDLED_LAB_SAMPLE_INTEGRITY_SOURCE_AND_NO_SYNTHESIS=PASS");
